        with open(gen_path, "w") as f:
            f.write(gen_src)
        compile(gen_src, gen_path, "exec")
        wire_src = emit_wire(num, desc, K, DIR)
        wire_path = os.path.join(HERE, "wire_bootcamp_b%s.py" % num)
        with open(wire_path, "w") as f:
            f.write(wire_src)
        compile(wire_src, wire_path, "exec")
