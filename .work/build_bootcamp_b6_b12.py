        "    _lp = %r" % (tuple(lp),),
        "    _rp = %r" % (tuple(rp),),
        "    _nL = int(clamp((t - 5) / 6) * len(_lp))",
        "    _nR = int(clamp((t - 12) / 6) * len(_rp))",
        "    dr.rectangle([120, 190, 600, 470], fill=(16, 16, 30), outline=GREEN, width=3)",
