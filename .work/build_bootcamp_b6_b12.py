ACC = {"bbg": "CYAN", "fireship": "MAGENTA", "3b1b": "TEAL", "primer": "CYAN", "story": "GOLD"}

def vd(slug, short, style, eng, title, sub, blurb, caps, l1, l2, d):
    return dict(slug=slug, short=short, style=style, eng=eng, title=title, sub=sub,
                blurb=blurb, caps=caps, l1=l1, l2=l2, d=d)

def _title_block(style, title, sub):
    a = ACC[style]
    if style == "story":
        return [
            "    txt(dr, (W // 2, 70), %s, font(F_BOLD, 40), GOLD, anchor=\"mm\")" % repr(title),
            "    txt(dr, (W // 2, 118), %s, font(F_SERIF, 24), DIM, anchor=\"mm\")" % repr(sub),
        ]
    if style == "3b1b":
        return [
            "    txt(dr, (W // 2, 70), %s, font(F_BOLD, 40), TEAL, anchor=\"mm\")" % repr(title),
            "    txt(dr, (W // 2, 118), %s, font(F_SANS, 24), DIM, anchor=\"mm\")" % repr(sub),
        ]
    return ["    bbg_title(dr, %s, %s)" % (repr(title), a)]

def _tail(l1, l2, y1, y2, serif=False):
    f = "F_SERIF" if serif else "F_SANS"
    return [
        "    if t > 19:",
        "        txt(dr, (W // 2, %d), %s, font(%s, 25), CREAM, anchor=\"mm\")" % (y1, repr(l1), f),
        "    if t > 23:",
        "        txt(dr, (W // 2, %d), %s, font(%s, 24), DIM, anchor=\"mm\")" % (y2, repr(l2), f),
    ]

# ---------------- engine: boxes (sequential system diagram) ----------------
def eng_boxes(sp):
    style, a = sp["style"], ACC[sp["style"]]
    boxes = sp["d"]
    L = ["    dr.rectangle([0, 0, W, H], fill=STYLE_BG[%r])" % style,
         "    dot_grid(dr)"] + _title_block(style, sp["title"], sp["sub"])
    L += [
        "    _boxes = %r" % (tuple(boxes),),
        "    _n = len(_boxes)",
        "    _w = 210 if _n <= 5 else 150",
        "    _gap = 30 if _n <= 5 else 18",
        "    _x0 = (W - (_n * _w + (_n - 1) * _gap)) // 2",
        "    _lit = int(clamp((t - 5) / 13) * _n)",
        "    _y0, _y1 = 270, 410",
        "    for _i, _b in enumerate(_boxes):",
        "        _x = _x0 + _i * (_w + _gap)",
        "        _on = _i < _lit",
        "        glow_box(dr, [_x, _y0, _x + _w, _y1], %s if _on else (40, 40, 60))" % a,
        "        dr.rectangle([_x, _y0, _x + _w, _y1], fill=(12, 18, 32),",
        "                     outline=%s if _on else DIM, width=3 if _on else 2)" % a,
        "        _lines = wrap_text(_b, font(F_BOLD, 20), _w - 24, dr)",
        "        _ly = (_y0 + _y1) // 2 - (len(_lines) - 1) * 14",
        "        for _ln, _line in enumerate(_lines):",
        "            txt(dr, (_x + _w // 2, _ly + _ln * 28), _line, font(F_BOLD, 20),",
        "                %s if _on else DIM, anchor=\"mm\")" % a,
        "        if _i < _lit - 1:",
        "            arrow(dr, _x + _w, (_y0 + _y1) // 2, _x + _w + _gap, (_y0 + _y1) // 2,",
        "                  GREEN if _on else DIM)",
    ]
    L += _tail(sp["l1"], sp["l2"], 500, 560, serif=(style == "story"))
    return L

