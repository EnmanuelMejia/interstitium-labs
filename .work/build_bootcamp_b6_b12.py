    left_label, lp, right_label, rp, verdict = sp["d"]
    L = ["    dr.rectangle([0, 0, W, H], fill=STYLE_BG[\"primer\"])",
         "    dot_grid(dr)"] + _title_block("primer", sp["title"], sp["sub"])
