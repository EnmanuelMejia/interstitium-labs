def scene_src(sp):
    name = "scene_" + sp["slug"].replace("-", "_")
    lines = ["def %s(t, dr, img):" % name] + ENG[sp["eng"]](sp)
    return "\n".join(lines) + "\n"

def video_entry(sp):
    caps = ",\n    ".join("(%d,%d,%s)" % (a, b, repr(c))
                          for a, b, c in zip((4, 10, 16, 22), (10, 16, 22, 26), sp["caps"]))
    return (" V(BOOTCAMP_K[%r], %r, %r, %s,\n"
            "   %s, %r, scene_%s,\n"
            "   %s,\n"
            "   [%s]),") % (sp["short"], sp["short"], sp["slug"], repr(sp["title"]),
                            repr(sp["sub"]), sp["style"],
                            sp["slug"].replace("-", "_"), repr(sp["blurb"]), caps)

